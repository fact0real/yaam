import AppKit
import Combine
import Foundation
import UniformTypeIdentifiers

/// Optional ADIF mirror for FT8/FT4 contacts which YAAM has already saved to
/// the active station logbook. The database remains the canonical log.
@MainActor
final class DigitalQSOArchiveStore: ObservableObject {
    static let shared = DigitalQSOArchiveStore()
    nonisolated private static let ioQueue = DispatchQueue(label: "app.yaam.ft8.archive", qos: .utility)
    private let bookmarkKey = "ft8SuccessfulQSOArchiveBookmark"

    @Published private(set) var archiveURL: URL?
    @Published private(set) var lastStatus = "Choose an ADIF file to keep a separate copy of successful FT8/FT4 contacts."

    private init() {
        archiveURL = resolveBookmark()
        if let archiveURL {
            lastStatus = "New successful FT8/FT4 contacts will be added to \(archiveURL.lastPathComponent)."
        }
    }

    func chooseArchiveFile() {
        let panel = NSSavePanel()
        panel.title = "Choose Successful QSO Archive"
        panel.message = "Choose or create an ADIF file. Newly completed FT8/FT4 QSOs will be appended after YAAM saves them to the active logbook."
        panel.prompt = "Use ADIF File"
        panel.nameFieldStringValue = "YAAM-Digital-Contacts.adi"
        panel.allowedContentTypes = [UTType(filenameExtension: "adi") ?? .data,
                                     UTType(filenameExtension: "adif") ?? .data]
        panel.canCreateDirectories = false
        panel.begin { [weak self] response in
            guard response == .OK, let url = panel.url else { return }
            self?.setArchiveURL(url)
        }
    }

    func disableArchive() {
        UserDefaults.standard.removeObject(forKey: bookmarkKey)
        archiveURL = nil
        lastStatus = "Separate ADIF archive is off. Successful contacts will continue to be saved in the YAAM logbook."
    }

    func appendSuccessfulContact(_ fields: [String: String]) {
        guard let url = archiveURL else { return }
        let scoped = url.startAccessingSecurityScopedResource()
        let store = self
        Self.ioQueue.async {
            defer { if scoped { url.stopAccessingSecurityScopedResource() } }
            do {
                try Self.write(fields: fields, to: url)
                Task { @MainActor in store.updateStatus("Saved successful contact to \(url.lastPathComponent).") }
            } catch {
                let detail = error.localizedDescription
                Task { @MainActor in
                    store.updateStatus("The contact is in the YAAM logbook, but the ADIF copy could not be written: \(detail)")
                }
            }
        }
    }

    private func setArchiveURL(_ url: URL) {
        do {
            if !FileManager.default.fileExists(atPath: url.path) {
                try Data("Generated by YAAM\r\n<EOH>\r\n".utf8).write(to: url, options: .atomic)
            }
            let bookmark = try url.bookmarkData(options: [.withSecurityScope],
                                                 includingResourceValuesForKeys: nil,
                                                 relativeTo: nil)
            UserDefaults.standard.set(bookmark, forKey: bookmarkKey)
            archiveURL = url
            lastStatus = "New successful FT8/FT4 contacts will be added to \(url.lastPathComponent)."
        } catch {
            lastStatus = "Could not save access to that ADIF file: \(error.localizedDescription)"
        }
    }

    private func updateStatus(_ status: String) {
        lastStatus = status
    }

    private func resolveBookmark() -> URL? {
        guard let bookmark = UserDefaults.standard.data(forKey: bookmarkKey) else { return nil }
        var stale = false
        guard let url = try? URL(resolvingBookmarkData: bookmark,
                                 options: [.withSecurityScope],
                                 relativeTo: nil,
                                 bookmarkDataIsStale: &stale) else { return nil }
        if stale, let renewed = try? url.bookmarkData(options: [.withSecurityScope],
                                                       includingResourceValuesForKeys: nil,
                                                       relativeTo: nil) {
            UserDefaults.standard.set(renewed, forKey: bookmarkKey)
        }
        return url
    }

    nonisolated private static func write(fields: [String: String], to url: URL) throws {
        let adif = generateADIF(originalContent: "", records: [fields])
        guard let eoh = adif.range(of: "<EOH>", options: .caseInsensitive) else {
            throw ArchiveError.invalidADIF
        }
        let recordText = String(adif[eoh.upperBound...]).trimmingCharacters(in: .whitespacesAndNewlines) + "\r\n"
        if FileManager.default.fileExists(atPath: url.path),
           let current = try? Data(contentsOf: url), !current.isEmpty {
            if let existingText = String(data: current, encoding: .utf8),
               let closingTag = existingText.range(of: "</ADIF>", options: .caseInsensitive) {
                let updated = String(existingText[..<closingTag.lowerBound])
                    + recordText + String(existingText[closingTag.lowerBound...])
                try Data(updated.utf8).write(to: url, options: .atomic)
            } else {
                let separator = current.last == 0x0A ? "" : "\r\n"
                let handle = try FileHandle(forWritingTo: url)
                defer { try? handle.close() }
                try handle.seekToEnd()
                try handle.write(contentsOf: Data((separator + recordText).utf8))
            }
        } else {
            let header = "Generated by YAAM\r\n<EOH>\r\n"
            try Data((header + recordText).utf8).write(to: url, options: .atomic)
        }
    }

    private enum ArchiveError: LocalizedError {
        case invalidADIF
        var errorDescription: String? { "YAAM could not format the contact as ADIF." }
    }
}
